"""Re-import the exported GLB into a fresh scene, sanity-check it and write ASSETS.md."""
import os
import bpy
from mathutils import Vector

PIVOTS = {
    'Stall': 'world origin; ground/plank floor y=0; counter top y=0.95 (x -0.95..0.95), counter front z=+0.55, back z=-0.05',
    'Noren_L': 'origin at top edge centre (sway pivot)', 'Noren_C': 'origin at top edge centre (sway pivot)',
    'Noren_R': 'origin at top edge centre (sway pivot)', 'Lantern': 'origin at hanging point (swing pivot)',
    'Crate': 'origin bottom centre', 'Chalkboard': 'origin at base centre',
    'Upgrade_Sign': 'world-placed (root at origin); hangs from right front post bracket',
    'Upgrade_Crate2': 'origin at its own bottom centre, placed right-front of stall (world coords)',
    'Upgrade_Banner': 'world-placed along roof front edge (root at origin)',
    'Chef': 'feet at origin, faces +Z; game places at z~-0.25',
    'Chef_Head': 'origin at neck', 'Chef_Eyes': 'origin at eye centre (scale Y to blink)',
    'Chef_Mouth': 'origin at mouth centre',
    'Chef_ArmL': 'origin at left shoulder (+X); rot.x -70deg = reach forward to counter',
    'Chef_ArmR': 'origin at right shoulder (-X); rot.z -130..-150deg = raised wave',
    'Apple': 'origin bottom centre', 'Apple_Body': 'spherical UV: u around, v 0 at top -> 1 at bottom',
    'Knife': 'origin at handle end, blade along +X, edge down (-Y)',
    'Spoon': 'origin at bowl centre, handle rises toward +X',
    'Stick': 'origin at bottom end, along +Y',
    'Juicer_Button': 'origin at button base (press along +Z -> -Z)',
    'Oven_Button': 'origin at button base', 'Oven_Dial': 'origin at dial base (rotate about Z)',
    'Oven_Glow': 'emissive plane inside window; animate visibility/scale',
    'Heat_Button': 'child of SyrupPan_Stove; origin at button base',
    'Juice_Straw': 'origin at the straw bottom end (inside glass)',
    'Juice_Garnish': 'origin on the glass rim',
    'Customer_D_Basket': 'child of Customer_D_ArmL; origin at the handle top (hangs on forearm)',
}


def gl(v):
    """Blender (Z-up) -> glTF (Y-up) coordinates."""
    return Vector((v.x, v.z, -v.y))


def bbox(o):
    lo = Vector((1e9, 1e9, 1e9))
    hi = -lo
    found = False

    def walk(x):
        nonlocal lo, hi, found
        if x.type == 'MESH':
            for c in x.bound_box:
                w = gl(x.matrix_world @ Vector(c))
                lo = Vector(map(min, lo, w))
                hi = Vector(map(max, hi, w))
                found = True
        for c in x.children:
            walk(c)
    walk(o)
    return (lo, hi) if found else (Vector(), Vector())


def mats(o):
    s = set()

    def walk(x):
        if x.type == 'MESH':
            s.update(m.name for m in x.data.materials if m)
        for c in x.children:
            walk(c)
    walk(o)
    return sorted(s)


def tris(o):
    n = 0
    if o.type == 'MESH':
        n += sum(len(p.vertices) - 2 for p in o.data.polygons)
    for c in o.children:
        n += tris(c)
    return n


def f3(v):
    return f'({v.x:.3f}, {v.y:.3f}, {v.z:.3f})'


def write(glb, out_md, roots_order):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bpy.ops.import_scene.gltf(filepath=glb)
    bpy.context.view_layer.update()
    roots = {o.name: o for o in bpy.context.scene.objects if o.parent is None}
    missing = [r for r in roots_order if r not in roots]
    assert not missing, missing
    # facing check on re-import: eyes / emblem must be at +Z (glTF) relative to their parents
    checks = []
    for n, p in (('Chef_Eyes', 'Chef_Head'), ('Customer_A_Eyes', 'Customer_A_Head'),
                 ('Customer_B_Eyes', 'Customer_B_Head'), ('Customer_C_Eyes', 'Customer_C_Head'),
                 ('Customer_D_Eyes', 'Customer_D_Head'), ('Juice_Emblem', 'Juice_Glass'),
                 ('Counter_Cloth', 'Stall_Frame')):
        e = gl(bpy.data.objects[n].matrix_world.translation)
        lo, hi = bbox(bpy.data.objects[p])
        ok = e.z > (lo.z + hi.z) / 2
        checks.append(f'{n} z={e.z:.3f} vs {p} centre z={(lo.z + hi.z) / 2:.3f} -> {"OK" if ok else "FAIL"}')
        assert ok, checks[-1]
    total = sum(tris(roots[r]) for r in roots_order)
    size = os.path.getsize(glb)
    L = []
    L.append('# Aomori Apple Kitchen - 3D asset manifest\n')
    L.append(f'File: `assets/aomori.glb` ({size / 1e6:.2f} MB, {total} triangles, {len(roots_order)} root nodes). '
             'Generated by `assets/blender/build_assets.py` (Blender 5.2 as a Python module; '
             '`python3 assets/blender/build_assets.py [--no-render] [--no-icons]`).\n')
    L.append('## Conventions\n')
    L.append('- glTF axes: **+Y up, metres, character/object fronts face +Z** (toward camera/customer). '
             'Character LEFT = +X, RIGHT = -X.')
    L.append('- Every item is a separate root node at the world origin (upgrades are world-placed). '
             'Roots of multi-part items are empty nodes; single-part items are the mesh itself.')
    L.append('- All meshes are flat-shaded (split normals); materials are plain Principled/PBR factors '
             '(no textures). Only `Apple_Body` carries a UV map (spherical: u around, v=0 top -> 1 bottom).')
    L.append('- Materials are shared by name across the file; the game can remap/tint by name '
             '(`M_AppleSkin`, `M_Jam` are meant to be re-tinted). `M_Glass` is alphaMode BLEND, alpha 0.28. '
             '`M_Lantern` is emissive (strength 0.6).')
    L.append('- Animation is node-based (no skins/bones): rotate arm/leg nodes about their shoulder/hip pivots, '
             'scale `*_Eyes` on Y to blink, sway `Noren_*` / `Lantern` about their top pivots.')
    L.append('- Arm poses (glTF Euler, radians shown in deg): reach to counter = ArmL/ArmR rotation.x = -70 deg; '
             'wave = Chef_ArmR rotation.z = -140 deg (raises the right arm up/outward). Customer legs: rotate .x '
             'about the hip for walking.')
    L.append('- Chef is ~1.65 m tall incl. beret (shoulders at 1.11 so her chest shows above the 0.95 counter). Kids 1.05-1.15 m, '
             'grandpa ~1.28 m.\n')
    L.append('Re-import check (facing): ' + '; '.join(checks) + '\n')
    L.append('## Root nodes\n')
    for r in roots_order:
        o = roots[r]
        lo, hi = bbox(o)
        d = hi - lo
        L.append(f'### {r}\n')
        L.append(f'- Size (x, y, z): **{d.x:.3f} x {d.y:.3f} x {d.z:.3f} m**; bbox min {f3(lo)} max {f3(hi)}; '
                 f'{tris(o)} tris')
        if r in PIVOTS:
            L.append(f'- Pivot: {PIVOTS[r]}')
        L.append(f'- Materials: {", ".join("`" + m + "`" for m in mats(o))}')
        kids = []

        def walk(x, depth):
            for c in sorted(x.children, key=lambda c: c.name):
                clo, chi = bbox(c)
                cd = chi - clo
                piv = gl(c.matrix_world.translation)
                note = f' - {PIVOTS[c.name]}' if c.name in PIVOTS else ''
                cm = ', '.join(mats(c)) if c.type == 'MESH' else ''
                kids.append(f'{"  " * depth}- `{c.name}` size {cd.x:.3f}x{cd.y:.3f}x{cd.z:.3f}, origin {f3(piv)}'
                            f'{note}{" [" + cm + "]" if cm else ""}')
                walk(c, depth + 1)
        walk(o, 0)
        if kids:
            L.append('- Children:')
            L += ['  ' + k for k in kids]
        L.append('')
    L.append('## Materials\n')
    allm = sorted({m.name for m in bpy.data.materials if m.users})
    L.append(', '.join(f'`{m}`' for m in allm) + '\n')
    L.append('## Icons and previews\n')
    L.append('- `public/icons/apple_<id>.png` (a048, a081, a023, a066, a006, a094, a091, a032, a058, a086), '
             '`dish_<recipeId>.png` (fresh_juice, rabbit_apples, apple_jam, hirosaki_pie, ringo_ame), '
             '`chef_portrait.png`, `customer_<A|B|C|D>_portrait.png` - 256x256 transparent PNG, 3/4 view.')
    L.append('- `assets/previews/*.png` - review renders (hero stall + chef, upgrades + customer, character lineup, '
             'each character, cut apples, tools, appliances in each state, each dish, juice front/side/top).')
    with open(out_md, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('manifest written', out_md, '|', '; '.join(checks))
