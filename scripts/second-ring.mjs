import { chromium } from '@playwright/test';
import { playBeats } from '../e2e/arcade-lib.mjs';
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
await page.goto('http://127.0.0.1:5173/');
await page.evaluate(() => localStorage.setItem('aomori-kitchen-save', JSON.stringify({ version: 2, completedOrders: 15 })));
await page.reload();
await page.click('[data-testid=open-practice]');
await page.click('[data-testid=practice-hirosaki_pie]');
await page.click('[data-testid=apple-a048]');
await page.click('[data-testid=confirm-apple]');
await page.waitForFunction(() => document.querySelector('.frame').dataset.sub === 'active');
await playBeats(page, { offsets: [0, 0, null] });
await page.waitForFunction(() => (window.__beats.i ?? 0) >= 2);
await page.waitForTimeout(150);
await page.screenshot({ path: `${out}_a.png` });
const info = await page.evaluate(() => window.__beats);
console.log(JSON.stringify(info));
await browser.close();
