import assert from 'node:assert/strict';
import fs from 'node:fs';
import {gradeTiming,summarizeTechnique,validateActionCatalog} from './timing_reference.mjs';
import {createAppleScoring} from './scoring_reference.mjs';
const read=n=>JSON.parse(fs.readFileSync(new URL(n,import.meta.url),'utf8'));
const c=read('recipe_actions_20.json'), p=read('prototype_game_data.json');
console.log(validateActionCatalog(c,p));
const t=c.recipes.find(r=>r.recipe_id==='hirosaki_pie').steps[0].timing;
for(const [offset,expected] of [[0,'Perfect'],[350,'Perfect'],[-350,'Perfect'],[351,'Good'],[800,'Good'],[801,'OK'],[1300,'OK'],[1301,'Miss']]) assert.equal(gradeTiming(t,t.target_ms+offset).grade,expected);
assert.equal(gradeTiming(t,null).grade,'Miss');
assert.equal(gradeTiming(t,t.duration_ms+1).grade,'Miss');
assert.equal(gradeTiming(t,t.target_ms,false).grade,'Miss');
assert.equal(gradeTiming(t,t.target_ms+1100,true,1.5).grade,'Good');
const make=(n,grade)=>Array.from({length:n},()=>({grade}));
assert.equal(summarizeTechnique(make(1,'Good')).techniqueBonus,1);
assert.equal(summarizeTechnique(make(5,'Good')).techniqueBonus,1);
assert.equal(summarizeTechnique(make(5,'OK')).executionPenalty,1);
assert.equal(summarizeTechnique([{grade:'Perfect'},{grade:'Miss'}]).executionPenalty,0);
assert.equal(summarizeTechnique([{grade:'Perfect'},{grade:'Miss'}]).techniqueBonus,0);
assert.equal(summarizeTechnique(make(5,'Miss'),{assisted:true}).techniqueBonus,1);
const broken=structuredClone(c);broken.recipes.find(r=>r.recipe_id==='baked_apple').steps[0].gesture='swipe';
assert.throws(()=>validateActionCatalog(broken,p),/Whole apple/);
const badCandy=structuredClone(c);badCandy.recipes.find(r=>r.recipe_id==='ringo_ame').steps[0].gesture='circle';
assert.throws(()=>validateActionCatalog(badCandy,p),/syrup/);
const s=createAppleScoring(p),tech=summarizeTechnique(make(5,'Good'));
assert.equal(s.evaluateOrder({appleId:'a048',recipeId:'hirosaki_pie',...tech}).stars,3);
assert.equal(s.fit('a032','rabbit_apples').fit_stars,0);
assert.equal(s.fit('a091','ringo_ame').fit_stars,3);
assert.equal(s.evaluateOrder({appleId:'a032',recipeId:'rabbit_apples',executionPenalty:1}).stars,0);
console.log('Passed: timing boundaries, invalid events, normalized technique, assistance, whole-fruit invariants, active scope and preserved fit examples. Gesture recognition/UI not tested here.');
